export type TikzLocale = 'pt-BR' | 'en';

const TIKZ_LOCALE_KEY = 'forjatikz_locale_v1';

export function detectTikzLocale(): TikzLocale {
  const saved = localStorage.getItem(TIKZ_LOCALE_KEY);
  if (saved === 'en' || saved === 'pt-BR') return saved;
  const sys = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  return sys.startsWith('pt') ? 'pt-BR' : 'en';
}

export function saveTikzLocale(loc: TikzLocale) {
  localStorage.setItem(TIKZ_LOCALE_KEY, loc);
}

