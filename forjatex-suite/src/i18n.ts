export type SuiteLocale = 'pt-BR' | 'en';

const SUITE_LOCALE_KEY = 'forjatex_suite_locale_v1';

export function detectSuiteLocale(): SuiteLocale {
  const saved = localStorage.getItem(SUITE_LOCALE_KEY);
  if (saved === 'en' || saved === 'pt-BR') return saved;
  const sys = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  return sys.startsWith('pt') ? 'pt-BR' : 'en';
}

export function saveSuiteLocale(loc: SuiteLocale) {
  localStorage.setItem(SUITE_LOCALE_KEY, loc);
}

